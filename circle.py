import math


def area(r):
    """
    Вычисляет площадь круга по его радиусу.

    Формула: S = π * r^2

    Параметры:
        r (float | int): радиус круга (r >= 0)

    Возвращает:
        float: площадь круга

    Пример вызова:
        >>> area(5)
        78.53981633974483
    """
    return math.pi * r * r


def perimeter(r):
    """
    Вычисляет длину окружности (периметр круга) по его радиусу.

    Формула: P = 2 * π * r

    Параметры:
        r (float | int): радиус круга (r >= 0)

    Возвращает:
        float: длина окружности

    Пример вызова:
        >>> perimeter(5)
        31.41592653589793
    """
    return 2 * math.pi * r