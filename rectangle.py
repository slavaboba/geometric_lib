def area(a, b):
    """
    Вычисляет площадь прямоугольника.

    Формула: S = a * b

    Параметры:
        a (float | int): длина первой стороны (a >= 0)
        b (float | int): длина второй стороны (b >= 0)

    Возвращает:
        float | int: площадь прямоугольника

    Пример вызова:
        >>> area(3, 5)
        15
    """
    return a * b


def perimeter(a, b):
    """
    Вычисляет периметр прямоугольника.

    Формула: P = 2 * a + 2 * b

    Параметры:
        a (float | int): длина первой стороны (a >= 0)
        b (float | int): длина второй стороны (b >= 0)

    Возвращает:
        float | int: периметр прямоугольника

    Пример вызова:
        >>> perimeter(3, 5)
        16
    """
    return 2 * a + 2 * b