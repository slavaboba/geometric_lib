def area(a):
    """
    Вычисляет площадь квадрата по длине его стороны.

    Формула: S = a^2

    Параметры:
        a (float | int): длина стороны квадрата (a >= 0)

    Возвращает:
        float | int: площадь квадрата

    Пример вызова:
        >>> area(4)
        16
    """
    return a * a


def perimeter(a):
    """
    Вычисляет периметр квадрата по длине его стороны.

    Формула: P = 4 * a

    Параметры:
        a (float | int): длина стороны квадрата (a >= 0)

    Возвращает:
        float | int: периметр квадрата

    Пример вызова:
        >>> perimeter(4)
        16
    """
    return 4 * a